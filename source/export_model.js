// Export the shared model to JSON for the Python engine (engine/cellsim/cell_model.json).
//   node export_model.js           write the file
//   node export_model.js --check   exit 1 if the file is not up to date with src/cell-model.js
const fs = require('fs');
const path = require('path');
const M = require('./src/cell-model.js');

const OUT = path.join(__dirname, '..', 'engine', 'cellsim', 'cell_model.json');

function modelJson() {
  const lint = M.lint();
  if (lint.length) throw new Error('model lint failed:\n' + lint.join('\n'));
  const data = {
    note: 'Generated by source/export_model.js from source/src/cell-model.js. Do not edit by hand.',
    T: M.T, TKIND: M.TKIND, TSRC: M.TSRC, TRANGE: M.TRANGE, RULES: M.RULES, CHECKPOINTS: M.CHECKPOINTS, SLOTS: M.SLOTS, SIGNALS: M.SIGNALS, CONST: M.CONST,
    RUNGS: M.RUNGS, PROPERTIES: M.PROPERTIES, OUTPUTS: M.OUTPUTS, JOBS: M.JOBS, MACHINES: M.MACHINES,
    SETUP_MACHINES: M.SETUP_MACHINES, KPI: M.KPI,
  };
  return JSON.stringify(data, null, 1) + '\n';
}

if (require.main === module) {
  let text;
  try { text = modelJson(); } catch (e) { console.error(e.message); process.exit(1); }
  if (process.argv.includes('--check')) {
    const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') : '';
    if (cur !== text) { console.error(`${OUT} is out of date: run node export_model.js`); process.exit(1); }
    console.log('model export up to date');
  } else {
    fs.mkdirSync(path.dirname(OUT), { recursive: true });
    fs.writeFileSync(OUT, text);
    console.log('written', OUT);
  }
}

module.exports = { modelJson, OUT };
