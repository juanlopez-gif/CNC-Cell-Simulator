// Step A2.1: which rule should fuse camera and proximity at each checkpoint?
//   node --max-old-space-size=10000 camera_study.js [outDir]
// For every checkpoint CP-1 ... CP-5 and every rule (camera, prox, present, absent, ask) it builds the
// abstract model with wrong readings at that checkpoint only (proximity wrong, camera false positive,
// camera false negative, stale image; one source wrong at a time), the other checkpoints keeping the
// rule of the model, and explores every reachable state. CP=<id,...> and RULES=<rule,...> narrow the
// table; FAULTS=<class,...> replaces the fault classes (default mismatch,camwrong).
// Writes camera_study.json and camera_study.md (default out/verification/).
const fs = require('fs');
const path = require('path');
const M = require('./src/cell-model.js');
const V = require('./src/cell-verify.js');

const OUT = process.argv[2] || path.join(__dirname, 'out', 'verification');
fs.mkdirSync(OUT, { recursive: true });
const ALL_RULES = ['camera', 'prox', 'present', 'absent', 'ask'];
const CPS = process.env.CP ? process.env.CP.split(',') : M.CHECKPOINTS.map((c) => c.id);
const RULES = process.env.RULES ? process.env.RULES.split(',') : ALL_RULES;
const FAULTS = process.env.FAULTS ? process.env.FAULTS.split(',') : ['mismatch', 'camwrong'];
const FILE = path.join(OUT, 'camera_study.json');
let runs = fs.existsSync(FILE) ? JSON.parse(fs.readFileSync(FILE, 'utf8')).runs : [];

// the label of the command that ends a trace: what went wrong at the checkpoint
const lastCheck = (trace, cp) => (trace || []).slice().reverse().find((l) => l.includes(cp + ' ')) || null;

for (const cp of CPS) for (const rule of RULES) {
  const ir = V.build(2, { faults: FAULTS, cps: [cp], rules: { [cp]: rule } });
  process.stdout.write(`${cp} ${rule}: ${ir.cmds.length} commands ... `);
  const t0 = Date.now();
  const r = V.check(ir, { maxStates: 30e6 });
  const failed = r.results.filter((x) => !x.ok);
  console.log(`${r.states} states, ${((Date.now() - t0) / 1000).toFixed(1)} s, failed: ${failed.map((x) => x.id).join(' ') || 'none'}, ${r.deadlocks} deadlocks`);
  runs = runs.filter((x) => !(x.cp === cp && x.rule === rule));
  runs.push({
    cp, rule, faults: FAULTS, states: r.states, seconds: (Date.now() - t0) / 1000, deadlocks: r.deadlocks,
    deadlock: r.deadlock && { at: lastCheck(r.deadlock.trace, cp), trace: r.deadlock.trace.slice(-12), state: r.deadlock.state },
    failed: failed.map((x) => ({ id: x.id, text: x.text, at: lastCheck(x.trace, cp), trace: x.trace && x.trace.slice(-12) })),
  });
}
const order = (x) => M.CHECKPOINTS.findIndex((c) => c.id === x.cp) * 10 + ALL_RULES.indexOf(x.rule);
runs.sort((a, b) => order(a) - order(b));
fs.writeFileSync(FILE, JSON.stringify({ date: new Date().toISOString().slice(0, 10), runs }, null, 1) + '\n');

// ---- report
const L = [];
L.push('# Camera policy study (step A2.1)', '');
L.push(`Generated by \`source/camera_study.js\` on ${new Date().toISOString().slice(0, 10)}. Each row is one exhaustive run of the abstract model of \`verification/results.md\` with wrong readings at **one** checkpoint (fault classes: ${FAULTS.join(', ')}: the proximity sensor wrong, or the camera wrong with a valid image — false positive, false negative or stale image; one source wrong at a time) and the rule of that checkpoint set as in the column; the other checkpoints read correctly. Every disagreement is counted as a mismatch, so three in the window still stop the line.`, '');
L.push('Rules: **camera** = the camera value is used (the rule of the model so far); **prox** = the proximity value is used; **present** / **absent** = that value is used whenever the two disagree (conservative fusion in that direction); **ask** = a disagreement stops the line, the operator looks, and after the reset the check is repeated (modelled with the camera-fault path).', '');
L.push('| Checkpoint | Rule | States | Failed properties | Deadlocks | Where it goes wrong |', '|---|---|---:|---|---:|---|');
runs.forEach((x) => {
  const where = Array.from(new Set(x.failed.map((f) => `${f.id}: ${f.at || '?'}`).concat(x.deadlocks ? [`deadlock: ${x.deadlock.at || '?'}`] : []))).join('; ');
  L.push(`| ${x.cp} | ${x.rule} | ${x.states.toLocaleString('en-US')} | ${x.failed.map((f) => f.id).join(' ') || 'none'} | ${x.deadlocks} | ${where} |`);
});
L.push('', 'L1–L3 fail whenever a deadlock is reachable (the cell can no longer make progress).', '');
fs.writeFileSync(path.join(OUT, 'camera_study.md'), L.join('\n'));
console.log('written', path.join(OUT, 'camera_study.md'));
