// Timed verification with UPPAAL (step A4.3, PROJECT_STATUS.md §5.17): runs verifyta on the two
// generated models and writes the results.
//   node timed_verify.js <path of verifyta> [out dir]
// For each model (verification/cell_setup2_timed.xml, case 1, and cell_setup2_timed_master.xml,
// case 2) every query of TM.queries() is checked on its own, with a limit of QUERY_MINUTES (default
// 20) per query; the raw output of verifyta goes to <out>/<model>.txt,
// the table of results to <out>/timed_results.md (default out dir: out/timed). It exits 1 when
// verifyta fails or a query is not satisfied. The licence of verifyta must be active already
// (verifyta --lease <hours> --key <key>, done by the workflow `timed verification`).
const fs = require('fs');
const path = require('path');
const { spawnSync } = require('child_process');
const TM = require('./src/cell-timed.js');

const verifyta = process.argv[2];
const OUT = path.resolve(process.argv[3] || path.join(__dirname, 'out', 'timed'));
if (!verifyta) { console.error('usage: node timed_verify.js <verifyta> [out dir]'); process.exit(2); }
fs.mkdirSync(OUT, { recursive: true });
const UNIT = TM.UNIT;
const CASES = [
  { file: 'cell_setup2_timed.xml', master: false, name: 'Case 1: no master check of the gauge after start-up' },
  { file: 'cell_setup2_timed_master.xml', master: true, name: 'Case 2: the 4-h master check may fall due' },
];

const ver = spawnSync(verifyta, ['--version'], { encoding: 'utf8' });
const version = ((ver.stdout || '') + (ver.stderr || '')).trim().split('\n')[0] || 'unknown';
const md = ['# Timed verification (UPPAAL)', '',
  'Generated by `source/timed_verify.js` in the workflow `timed verification` (step A4.3, PROJECT_STATUS.md §5.17).',
  `Models: \`verification/cell_setup2_timed*.xml\`, generated by \`source/src/cell-timed.js\`. verifyta: ${version}.`,
  `Time unit of the models: ${UNIT} s; the values below are given in s.`, ''];
let failed = false;
const LIMIT = Number(process.env.QUERY_MINUTES || 20) * 60000;   // per query
for (const c of CASES) {
  const qs = TM.queries(TM.network({ master: c.master }));
  const model = path.join(__dirname, '..', 'verification', c.file);
  md.push(`## ${c.name}`, '', `\`verification/${c.file}\`, ${qs.length} queries, each run on its own with a limit of ${LIMIT / 60000} min.`, '',
    '| # | Query | Meaning | Result | Time |', '|---|---|---|---|---|');
  const log = [];
  qs.forEach((q, k) => {
    // one query per run: a query that does not finish in the limit does not stop the others
    const qf = path.join(OUT, 'query.q');
    fs.writeFileSync(qf, q.f + '\n');
    const t0 = Date.now();
    const r = spawnSync(verifyta, [model, qf], { encoding: 'utf8', maxBuffer: 1 << 28, timeout: LIMIT, killSignal: 'SIGKILL' });
    const secs = ((Date.now() - t0) / 1000).toFixed(1);
    const raw = (r.stdout || '') + (r.stderr || '');
    log.push(`==== query ${k + 1}: ${q.f} (${secs} s, exit ${r.status}${r.signal ? ', killed at the limit' : ''})`, raw);
    const lines = raw.split('\n').map((l) => l.replace(/^\s*-- /, '').trim()).filter(Boolean);
    const ok = lines.some((l) => /Formula is satisfied/i.test(l));
    // a sup / inf query also prints its value, in time units: shown in s
    const vals = lines.filter((l) => /^(sup|inf)/i.test(l)).map((l) => l.replace(/-?\d+(\.\d+)?$/, (n) => `${n} (${(Number(n) * UNIT).toFixed(2)} s)`));
    const text = r.signal ? '**not finished in the limit**' : ok ? ['satisfied'].concat(vals).join('; ')
      : '**' + (lines.filter((l) => /not satisfied|error|may be/i.test(l)).join(' ').slice(0, 300) || 'no result') + '**';
    if (!ok) failed = true;
    md.push(`| ${k + 1} | \`${q.f.replace(/\|/g, '\\|')}\` | ${q.c} | ${text.replace(/\|/g, '\\|')} | ${secs} s |`);
    console.log(`${c.file} query ${k + 1}/${qs.length} ${q.f}: ${text} (${secs} s)`);
  });
  fs.writeFileSync(path.join(OUT, c.file.replace(/\.xml$/, '.txt')), log.join('\n'));
  md.push('');
}
fs.writeFileSync(path.join(OUT, 'timed_results.md'), md.join('\n'));
process.exit(failed ? 1 : 0);
