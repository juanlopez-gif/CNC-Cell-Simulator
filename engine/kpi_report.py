"""The KPI measures of step A2.4 for nominal and faulty runs, written to kpi_report.md.

    python kpi_report.py                   8 h runs: nominal and 5 seeds with random disturbances
    python kpi_report.py --hours 2 --seeds 2
"""
import argparse
import time

from cellsim import run_random
from cellsim.sim import LOSS_CAUSES


def run(hours, faults, seed):
    sim, injected, actions = run_random(2, hours, faults=faults, seed=seed)
    if sim.errors:
        raise SystemExit(f"model disagreement in seed {seed}: {sim.errors[:3]}")
    return sim.measures(), injected


def table(cols):
    """cols: [(title, measures)]"""
    def f(v, d=1):
        return "-" if v is None else f"{v:.{d}f}"
    rows = [
        ("Nominal exchange idle per part (model; Setup 1 baseline)", lambda m: f'{f(m["nominal_exchange_idle_s"])} s ({f(m["baseline_exchange_idle_s"])} s)'),
        ("Mean CNC idle per part (measured)", lambda m: f'{f(m["mean_cnc_idle_s"])} s'),
        ("Time not machining", lambda m: f'{f(m["not_machining_s"] / 60)} min ({f(100 - 100 * m["machining_share"])} %)'),
        ("Parts per hour (good + NOK)", lambda m: f(m["parts_per_hour"])),
        ("Good parts per hour", lambda m: f(m["good_parts_per_hour"])),
    ] + [(f"Lost: {c}" if c != "exchange" else "Normal part exchange", (lambda c: lambda m: f(m["lost_s"][c] / 60))(c)) for c in LOSS_CAUSES] + [
        ("Exchange minus nominal exchange × cycles", lambda m: f'{f(m["exchange_beyond_nominal_s"] / 60)}'),
    ]
    out = ["| Measure | " + " | ".join(t for t, _ in cols) + " |", "|---|" + "---:|" * len(cols)]
    for name, fn in rows:
        unit = " (min)" if name.startswith(("Lost", "Normal", "Exchange minus")) else ""
        out.append(f"| {name}{unit} | " + " | ".join(fn(m) for _, m in cols) + " |")
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser(description="KPI measures of step A2.4")
    ap.add_argument("--hours", type=float, default=8.0)
    ap.add_argument("--seeds", type=int, default=5)
    ap.add_argument("--out", default="kpi_report.md")
    a = ap.parse_args()
    t0 = time.time()
    cols, notes = [], []
    m, _ = run(a.hours, False, 1)
    cols.append(("Nominal", m))
    for seed in range(1, a.seeds + 1):
        m, injected = run(a.hours, True, seed)
        cols.append((f"Faults, seed {seed}", m))
        notes.append(f"- seed {seed}: " + ", ".join(f"{k} {v}" for k, v in sorted(injected.items())))
    text = "\n".join([
        "# KPI measures (step A2.4)",
        "",
        f"Generated by `engine/kpi_report.py` (Python engine, Setup 2), {a.hours:g} h of simulated time per run.",
        "Definitions in PROJECT_STATUS.md §5.15. Every instant in which the CNC is not machining is charged",
        "to the first cause that applies: " + " > ".join(LOSS_CAUSES) + ".",
        "The runs with faults use the random disturbances of `run_random` (about one every 14 min, and the",
        "operator is sometimes away): a stress test of the logic, not an estimate of real fault rates.",
        "",
        table(cols),
        "",
        "Disturbances injected:",
        "",
        *notes,
        "",
    ])
    with open(a.out, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    print(text)
    print(f"written {a.out} in {time.time() - t0:.0f} s")


if __name__ == "__main__":
    main()
